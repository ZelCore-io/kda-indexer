// Generates crates/kdx-graphql/src/stock_schema.rs from the stock Kadena GraphQL indexer's
// schema (hack-a-chain-software/indexer-kadena, indexer/src/kadena-server/config/schema.graphql).
//
// The schema is built the way stock builds it (@graphql-tools/schema makeExecutableSchema,
// which merges the duplicated type definitions), with the versions stock's yarn.lock pins:
//
//   npm i graphql@16.10.0 @graphql-tools/schema@10.0.6
//   node scripts/stock-schema/extract.js <node_modules dir> <schema.graphql> <commit> \
//     > crates/kdx-graphql/src/stock_schema.rs
'use strict';
const path = require('path');
const fs = require('fs');
const [nm, sdlPath, commit] = process.argv.slice(2);
const { makeExecutableSchema } = require(path.join(nm, '@graphql-tools/schema'));
const g = require(path.join(nm, 'graphql'));
const schema = makeExecutableSchema({ typeDefs: fs.readFileSync(sdlPath, 'utf8') });
const directive = schema.getDirective('complexity');
const q = (s) => JSON.stringify(s);
const fields = [];
const abstract = [];
const names = Object.keys(schema.getTypeMap()).filter((n) => !n.startsWith('__')).sort();
for (const n of names) {
  const t = schema.getType(n);
  if (g.isAbstractType(t)) {
    abstract.push([n, schema.getPossibleTypes(t).map((x) => x.name).sort()]);
  }
  if (!(g.isObjectType(t) || g.isInterfaceType(t))) continue;
  for (const f of Object.values(t.getFields())) {
    let list = 0;
    for (let x = f.type; x; ) {
      if (g.isListType(x)) { list++; x = x.ofType; }
      else if (g.isNonNullType(x)) x = x.ofType;
      else break;
    }
    const v = f.astNode ? g.getDirectiveValues(directive, f.astNode) : undefined;
    const cx = v
      ? `Some(Directive { value: ${v.value}, multipliers: &[${(v.multipliers || []).map(q).join(', ')}] })`
      : 'None';
    const defaults = f.args
      .filter((a) => typeof a.defaultValue === 'number')
      .map((a) => `(${q(a.name)}, ${a.defaultValue})`);
    fields.push(
      `    StockField { coord: ${q(`${n}.${f.name}`)}, named: ${q(g.getNamedType(f.type).name)}, ` +
        `list_depth: ${list}, complexity: ${cx}, int_defaults: &[${defaults.join(', ')}] },`,
    );
  }
}
const out = [];
out.push(`//! Generated by \`scripts/stock-schema/extract.js\` from the stock indexer's schema`);
out.push(`//! (hack-a-chain-software/indexer-kadena @ ${commit},`);
out.push(`//! \`indexer/src/kadena-server/config/schema.graphql\`). Do not edit by hand.`);
out.push('');
out.push('/// A `@complexity(value, multipliers)` directive on a stock field.');
out.push('#[derive(Debug, Clone, Copy, PartialEq, Eq)]');
out.push('pub struct Directive {');
out.push('    pub value: i64,');
out.push('    pub multipliers: &\'static [&\'static str],');
out.push('}');
out.push('');
out.push('/// One field of a stock object or interface type.');
out.push('#[derive(Debug, Clone, Copy, PartialEq, Eq)]');
out.push('pub struct StockField {');
out.push('    /// `Type.field`.');
out.push('    pub coord: &\'static str,');
out.push('    /// The named (unwrapped) return type.');
out.push('    pub named: &\'static str,');
out.push('    /// List wrappers of the return type (`[[T!]]` is 2).');
out.push('    pub list_depth: u8,');
out.push('    pub complexity: Option<Directive>,');
out.push('    /// Integer argument defaults (the ones a multiplier can read).');
out.push('    pub int_defaults: &\'static [(&\'static str, i64)],');
out.push('}');
out.push('');
out.push(`/// The stock commit the table comes from.`);
out.push(`pub const STOCK_COMMIT: &str = ${q(commit)};`);
out.push('');
out.push('/// Every field of stock\'s object and interface types, sorted by type.');
out.push('pub const FIELDS: &[StockField] = &[');
out.push(...fields);
out.push('];');
out.push('');
out.push('/// Stock\'s interfaces and unions, with their possible types.');
out.push('pub const ABSTRACT: &[(&str, &[&str])] = &[');
for (const [n, ps] of abstract) out.push(`    (${q(n)}, &[${ps.map(q).join(', ')}]),`);
out.push('];');
process.stdout.write(out.join('\n') + '\n');
